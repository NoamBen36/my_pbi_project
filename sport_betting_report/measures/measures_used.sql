Sport GGR = 
CALCULATE(
    SUM(sports_fact_bet[stake_amount]) -
    SUM(sports_fact_bet[payout_amount]),
    KEEPFILTERS(sports_fact_bet[bet_status] = "Settled"
    )
)
/* 
Gross Gaming Revenue is calculated by subtracting the payout from the stake
We only want the GGR for the settled bets, not the opened one
*/


