WinRatio = 
 VAR SettledBetsCount =
 CALCULATE(COUNTROWS(sports_fact_bet),
 sports_fact_bet[bet_status] = "Settled"
 )

 VAR WinCount = 
SUM(sports_fact_bet[is_win_flag]
 )

 RETURN
 DIVIDE(WinCount, SettledBetsCount, 0)


