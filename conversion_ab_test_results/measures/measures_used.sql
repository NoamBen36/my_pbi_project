Converted And Bonus% = 
// Percentage among the converted of the ones who took the Welcome Bonus
DIVIDE(
    [WO opted in],
    [Converted Count],
    0
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Converted Count = 
CALCULATE(
    COUNTROWS(ab_test_welcome_offer_fr),
    FILTER(ab_test_welcome_offer_fr, 
    ab_test_welcome_offer_fr[converted] =1)
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Converted% = 
DIVIDE(
    [Converted Count],
    [Visitors Count],
    0
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/
Converted% (Group A) = 

VAR Targeted =
CALCULATE(
    COUNTROWS(ab_test_welcome_offer_fr),
    FILTER(ab_test_welcome_offer_fr, ab_test_welcome_offer_fr[test_group] = "A")
)

VAR Converted =
CALCULATE(
    COUNTROWS(ab_test_welcome_offer_fr),
    FILTER(ab_test_welcome_offer_fr, ab_test_welcome_offer_fr[test_group] = "A" && ab_test_welcome_offer_fr[converted] =1)
)

RETURN
DIVIDE(
    Converted,
    Targeted,
    0
)


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Converted% (Group B) = 

VAR Targeted =
CALCULATE(
    COUNTROWS(ab_test_welcome_offer_fr),
    FILTER(ab_test_welcome_offer_fr, ab_test_welcome_offer_fr[test_group] = "B")
)

VAR Converted =
CALCULATE(
    COUNTROWS(ab_test_welcome_offer_fr),
    FILTER(ab_test_welcome_offer_fr, ab_test_welcome_offer_fr[test_group] = "B" && ab_test_welcome_offer_fr[converted] =1)
)

RETURN
DIVIDE(
    Converted,
    Targeted,
    0
)


