Active Players = 
DISTINCTCOUNT(fact_activity[player_id])


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Cohort Size = 
CALCULATE(
    DISTINCTCOUNT(dim_player[player_id]),
    REMOVEFILTERS(dim_calendar)   -- ignore any date filters
)

/*
This is used to count the players in the cohort row 
i.e. how many players opened an account
*/


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Lifetime Activity Count = 
CALCULATE(
    COUNTROWS(fact_activity),
    REMOVEFILTERS(dim_calendar)
)


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

MA/Active Rate = 
DIVIDE(
    [Multi Active Players (Lifetime)],
    [Active Players],
    0
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Multi Active Players (Lifetime) = 
COUNTROWS(
    FILTER(
        VALUES(dim_player[player_id]),
        CALCULATE(
            COUNTROWS(fact_activity),
            REMOVEFILTERS(dim_calendar)
        ) >= 2
    )
)


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

New Players (Opened in Period) = 
CALCULATE(
    DISTINCTCOUNT(dim_player[player_id]),
    USERELATIONSHIP(dim_calendar[Date], dim_player[open_date])
    //Inactive relationship between tables
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Retained Players = 
DISTINCTCOUNT(fact_activity[player_id])


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Retention % = 
DIVIDE(
    [Retained Players],
    [Cohort Size]
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/
Single Active Players (Lifetime) = 
COUNTROWS(
    FILTER(
        VALUES(dim_player[player_id]),
        CALCULATE(
            COUNTROWS(fact_activity),
            REMOVEFILTERS(dim_calendar)
        ) = 1
    )
)

