Sport All Revenue = 
CALCULATE(
    SUM(sports_fact_bet[stake_amount]) -
    SUM(sports_fact_bet[payout_amount])
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Sport All Revenue Target = 
// For the example, we establish the target at previous month revenue + 10%
VAR AllRevenue =
CALCULATE(
    SUM(sports_fact_bet[stake_amount]) -
    SUM(sports_fact_bet[payout_amount])
)
VAR PreviousMonthRevenue =
CALCULATE(
    AllRevenue,
    DATEADD(
        dim_calendar[Date],
        -1,
        MONTH
    )
)

RETURN
PreviousMonthRevenue + (PreviousMonthRevenue * 0.10)

