***********************************************************************************************
***********************************************************************************************/


Sport Potential Payout = 
CALCULATE(
    SUMX(
        sports_fact_bet,
        sports_fact_bet[stake_amount] * sports_fact_bet[odds_taken_decimal]
    ),
    KEEPFILTERS( sports_fact_bet[bet_status] = "Open" )
)

/*
To calculate the potential payout, we only look at open bets
We multiply the stake with the odds
*/



/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Sport Realised Revenue = 
CALCULATE(
    [Sport GGR],
    KEEPFILTERS( sports_fact_bet[bet_status] = "Settled" )
)

    


