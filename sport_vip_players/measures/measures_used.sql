Bets = 
 COUNTROWS(
    fact_bet_last_2y
 )

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Netwin = 
 SUM(
    fact_bet_last_2y[ngr_usd]
 )
/*
An active sport user is a user with at least one sport session
within the selected period.
We use DISTINCTCOUNT to avoid double-counting returning users.
*/


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Netwin MoM % = 
    DIVIDE(
        [Netwin MTD] - [NetWin MTD Previous Month],
        ABS([NetWin MTD Previous Month])
)

//Using ABS to cater for negative Netwins
 

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Netwin MTD = 

VAR Netwin =
SUM(fact_bet_last_2y[ngr_usd])
RETURN

CALCULATE(
    Netwin,
    DATESMTD(
        dim_date[Date].[Date])
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

NetWin MTD Previous Month = 
CALCULATE(
    [Netwin MTD],
    DATEADD(
        dim_date[Date],
        -1,
        MONTH
    ))

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Payout = 
SUM(
    fact_bet_last_2y[payout_usd]
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/
Payout MoM % = 
    DIVIDE(
        [Payout MTD] - [Payout MTD Previous Month],
        [Payout MTD Previous Month]
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Payout MTD = 
CALCULATE(
    [Payout],
    DATESMTD(
        dim_date[Date])
)


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/
Payout MTD Previous Month = 
CALCULATE(
    [Payout MTD],
    DATEADD(
        dim_date[Date],
        -1,
        MONTH
    )
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/


Stake = 
SUM(
    fact_bet_last_2y[stake_usd]
)

/*
To calculate the potential payout, we only look at open bets
We multiply the stake with the odds
*/



/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Stake MoM % = 
    DIVIDE(
        [Stake MTD] - [Stake MTD Previous Month],
        [Stake MTD Previous Month]
)
    


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/


Stake MTD = 
 CALCULATE(
    [Stake],
    DATESMTD(dim_date[Date]
    )
 )


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Stake MTD Previous Month = 
CALCULATE(
    [Stake MTD],
    DATEADD(
        dim_date[Date],
        -1,
        MONTH
    ))


