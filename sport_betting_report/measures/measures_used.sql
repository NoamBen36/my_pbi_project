Sport Active Users = 
DISTINCTCOUNT(
    sports_fact_bet[user_id]
)
/*
An active sport user is a user with at least one sport session
within the selected period.
We use DISTINCTCOUNT to avoid double-counting returning users.
*/


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Sport Active Users Target = 

VAR PreviousMonthActive =
CALCULATE(
    [Sport Active Users],
    DATEADD(dim_calendar[Date], -1, MONTH)
)
VAR TenPerCent =
PreviousMonthActive * 0.1
RETURN

PreviousMonthActive + TenPerCent

