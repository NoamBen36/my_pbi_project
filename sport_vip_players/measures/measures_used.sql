Users = 
 DISTINCTCOUNT(
    fact_bet_last_2y[player_id]
 )


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Users MoM % = 
    DIVIDE(
        [Users MTD] - [Users MTD Previous Month],
        [Users MTD Previous Month]
)


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Users MTD = 
 CALCULATE(
    [Users],
    DATESMTD(
        dim_date[Date]
    )
 )


/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/


Users MTD Previous Month = 
CALCULATE(
    [Users MTD],
    DATEADD(
        dim_date[Date],
        -1,
        MONTH
    )
)

