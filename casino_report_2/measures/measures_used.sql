Casino ARPU = 
DIVIDE(
    [Casino GGR], [Casino Active Users]
)

/**********************************************************************************************
***********************************************************************************************
***********************************************************************************************/

Casino ARPU MTD = 

VAR ActiveUsersMTD =
    CALCULATE([Casino Active Users], DATESMTD(dim_calendar[Date]))

VAR GrossRevenueMTD =
    CALCULATE([Casino GGR], DATESMTD(dim_calendar[Date]))
    
RETURN
DIVIDE(GrossRevenueMTD, ActiveUsersMTD)


